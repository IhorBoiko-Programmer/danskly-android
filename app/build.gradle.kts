// Optional local settings (never committed): ai.serverUrl, release signing.
val localProps = Properties().apply {
    rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use(::load)
}
fun setting(name: String, env: String): String? =
    localProps.getProperty(name) ?: System.getenv(env)?.takeIf { it.isNotBlank() }

android {
    namespace = "app.danskly"
    // AndroidX 2026.11 libraries need the Android 17 (37.1) SDK to compile against.
    // The app still targets API 36, which is what Google Play requires.
    compileSdk {
        version = release(37) { minorApiLevel = 1 }
    }

    defaultConfig {
        applicationId = "app.danskly"
        minSdk = 26
        targetSdk = 36
        versionCode = (System.getenv("VERSION_CODE") ?: "1").toInt()
        versionName = "1.1.0"
        // Address of the Danskly AI server (see danskly-server). Can also be changed in the app settings.
        buildConfigField("String", "AI_SERVER_URL", "\"${setting("ai.serverUrl", "DANSKLY_AI_URL") ?: ""}\"")
    }

    signingConfigs {
        val keystore = setting("release.keystore", "RELEASE_KEYSTORE_PATH")
        if (keystore != null) {
            create("release") {
                storeFile = file(keystore)
                storePassword = setting("release.storePassword", "RELEASE_STORE_PASSWORD")
                keyAlias = setting("release.keyAlias", "RELEASE_KEY_ALIAS")
                keyPassword = setting("release.keyPassword", "RELEASE_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            // Without an upload key the release build is signed with the debug key, so it can still be installed for testing.
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            all {
                it.maxHeapSize = "3g"
                it.systemProperty("robolectric.pixelCopyRenderMode", "hardware")
                it.testLogging {
                    events("failed")
                    exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
                    showStackTraces = true
                }
            }
        }
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }
}

